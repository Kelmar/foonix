/********************************************************************************************************************/
/*
 * x86 specific instructions.
 */
namespace x86
{
    // Instructions specific to the x86 family.

    static inline
    void cpuid(uint32_t level, uint32_t& eax, uint32_t& ebx, uint32_t& ecx, uint32_t& edx)
    {
        __asm__(
            "cpuid\n\t"
            : "=a"(eax), "=b"(ebx), "=c"(ecx), "=d"(edx)
            : "0"(level)
        );
    }
}

