/********************************************************************************************************************/

#include <stddef.h>
#include <string.h>

/********************************************************************************************************************/

int PREFIX_(strncmp)(const char *s1, const char *s2, size_t size)
{
    for (size_t i = 0; i < size; ++i)
    {
        int diff = (int)s1[i] - (int)s2[i];

        if (diff != 0)
            return diff;

        if (s1[i] == '\0')
            return 0;
    }

    return 0;
}

